-- 执行方式：Supabase 控制台 → SQL Editor → 整段粘贴 → Run（只跑一次即可）
-- 幂等：按「昵称 + 金额」判重，重复执行不会产生重复行。
-- 日期：页面不展示日期，paid_on 统一记执行当天，仅供后台「本月」汇总用。
