insert into public.sponsors (nick, amount, paid_on)
select v.nick, v.amount, current_date
from (values
  ('*陈',                    6.00),
  ('**祥',                  20.00),
  ('*逸',                   30.00),
  ('*铭',                    1.88),
  ('*霜',                   30.00),
  ('*旭',                    5.00),
  ('*宇',                   10.00),
  ('*诗',                    0.66),
  ('w*w',                   20.00),
  ('*D',                    20.00),
  ('*条',                   20.00),
  ('L*t',                    5.00),
  ('一包鼠条',                5.00),
  ('马三三见好就收',           2.00),
  ('杜康',                  20.00),
  ('岁月留余香，心间存暖阳',   10.00)
) as v(nick, amount)
where not exists (
  select 1 from public.sponsors s
  where s.nick = v.nick and s.amount = v.amount
);

